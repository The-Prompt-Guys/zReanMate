// PowerPoint
// ---------------------------------------------------------------------------

/**
 * Slide order comes from the presentation's relationships, for the same reason
 * sheet order does: `slide12.xml` is a file name, not a position. Reordering a
 * deck in PowerPoint rewrites the relationship list and leaves the file names
 * alone, so numbering by file name would cite the wrong slide.
 */
const slidePaths = (zip) => {
  const presentation = textOf(zip, 'ppt/presentation.xml');
  const relsXml = textOf(zip, 'ppt/_rels/presentation.xml.rels');

  if (presentation && relsXml) {
    const relationships = new Map();
    for (const rel of relsXml.match(/<Relationship\s[^>]*\/?>/g) ?? []) {
      const id = attribute(rel, 'Id');
      const target = attribute(rel, 'Target');
      if (id && target) relationships.set(id, target.replace(/^\.\.\//, '').replace(/^\//, ''));
    }

    const ordered = [];
    for (const sldId of presentation.match(/<(?:[a-zA-Z0-9]+:)?sldId\s[^>]*\/?>/g) ?? []) {
      const relationshipId = attribute(sldId, 'r:id') ?? attribute(sldId, 'id');
      const target = relationshipId ? relationships.get(relationshipId) : null;
      if (target) ordered.push(target.startsWith('ppt/') ? target : `ppt/${target}`);
    }
    if (ordered.length > 0) return ordered;
  }

  // Fallback for a deck without a readable relationship list: file order, but
  // sorted NUMERICALLY, or slide10 sorts before slide2.
  return Object.keys(zip)
    .filter((path) => /^ppt\/slides\/slide\d+\.xml$/.test(path))
    .sort((a, b) => {
      const n = (p) => Number.parseInt(/(\d+)\.xml$/.exec(p)[1], 10);
      return n(a) - n(b);
    });
};

/**
 * Finds a slide's speaker notes, through that slide's own relationships.
 *
 * Deriving the path from the slide number does not work, and fails quietly
 * when it does: only slides that HAVE notes get a notesSlide, so a deck with
 * notes on slides 3, 5, 7 and 9 stores them as notesSlide1 through 4. Pairing
 * them by number attaches slide 3's notes to slide 1 — plausible-looking text
 * on the wrong slide, which is worse than no notes at all.
 *
 * The part name is also `notesSlide1.xml`, capital S; a lowercased guess finds
 * nothing on a case-sensitive lookup and silently yields no notes.
 */
const notesFor = (zip, slidePath) => {
  const name = slidePath.split('/').pop();
  const relsXml = textOf(zip, `ppt/slides/_rels/${name}.rels`);
  if (!relsXml) return null;

  for (const rel of relsXml.match(/<Relationship\s[^>]*\/?>/g) ?? []) {
    if (!/notesSlide$/.test(attribute(rel, 'Type') ?? '')) continue;
    const target = attribute(rel, 'Target');
    if (!target) continue;
    // Targets are relative to ppt/slides/, so "../notesSlides/notesSlide1.xml".
    const path = target.replace(/^\.\.\//, 'ppt/').replace(/^\//, '');
    return textOf(zip, path.startsWith('ppt/') ? path : `ppt/slides/${path}`);
  }
  return null;
};

/**
 * One slide becomes one numbered section: its own text, then its speaker notes.
 *
 * The notes are included because on a lecture deck they are frequently where
 * the actual explanation lives — the slide says "Normalization: 3 rules" and
 * the notes say what the three rules are. Dropping them would throw away the
 * more useful half of the file.
 */
const extractPptx = (zip) => {
  const sections = [];

  slidePaths(zip).forEach((path, index) => {
    const xml = textOf(zip, path);
    if (xml === null) return;

    // <a:t> is the DrawingML text run — the same element for a title, a bullet
    // and a text box, which is why paragraphs are recovered from <a:p> instead.
    const lines = elements(xml, 'p')
      .map((paragraph) => textRuns(paragraph, 't').join('').replace(/\s+/g, ' ').trim())
      .filter(Boolean);

    const slideNumber = index + 1;
    const notesXml = notesFor(zip, path);
    const notes = notesXml
      ? elements(notesXml, 'p')
          .map((paragraph) => textRuns(paragraph, 't').join('').replace(/\s+/g, ' ').trim())
          .filter(Boolean)
          // PowerPoint puts the slide number itself in the notes placeholder;
          // it is not content and would just repeat as a stray digit.
          .filter((line) => line !== String(slideNumber))
      : [];

    const body = [
      lines.join('\n'),
      notes.length > 0 ? `Speaker notes: ${notes.join(' ')}` : '',
    ]
      .filter(Boolean)
      .join('\n')
      .trim();

    if (body) {
      // Numbered by POSITION IN THE DECK, not by how many slides survived.
      // A slide that is only a picture yields no text and is dropped, and
      // numbering by the surviving count would silently shift every slide
      // after it — a citation reading "slide 5" would open slide 6. The
      // numbers are allowed to skip instead.
      sections.push({ number: slideNumber, title: lines[0] ?? null, text: body });
    }
  });

  return sections;
};

