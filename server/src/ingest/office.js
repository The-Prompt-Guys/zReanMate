// Format detection and entry point
// ---------------------------------------------------------------------------

/**
 * Identifies an OOXML package by what is inside it rather than by its name.
 *
 * A file renamed from .xlsx to .docx passes every check made before this one —
 * the extension matches what the browser claimed and the magic bytes say "ZIP",
 * which is true of all three formats. Reading the package tells the truth, and
 * turns a confusing parse failure into an accurate message.
 */
export const detectOoxmlFormat = (zip) => {
  if (entry(zip, 'word/document.xml')) return 'docx';
  if (entry(zip, 'xl/workbook.xml')) return 'xlsx';
  if (entry(zip, 'ppt/presentation.xml')) return 'pptx';
  return null;
};

/** Maps a stored mime type to the format key this module extracts by. */
export const formatForMimeType = (mimeType) => {
  if (PLAIN_TEXT_MIME_TYPES.has(mimeType)) return 'text';
  return Object.keys(OFFICE_FORMATS).find((key) => OFFICE_FORMATS[key].mimeType === mimeType) ?? null;
};

/**
 * Extracts text from a document.
 *
 * Returns the same shape the PDF extractor does, with `sections` in place of
 * `pages`, so the ingest service treats a deck and a PDF the same way.
 *
 * @param {string|Buffer} source   File path, or the bytes themselves.
 * @param {{ mimeType?: string, planTier?: string }} [options]
 */
export const extractDocument = async (source, { mimeType, planTier = 'free' } = {}) => {
  const buffer = Buffer.isBuffer(source) ? source : await readFile(source);

  if (buffer.length === 0) {
    throw new IngestError(
      INGEST_ERROR_CODES.EXTRACT_FAILED,
      'This file is empty. Please upload it again.',
    );
  }

  const claimed = formatForMimeType(mimeType);
  let format = claimed;
  let sections;

  if (claimed === 'text') {
    sections = extractPlainText(buffer);
  } else {
    let zip;
    try {
      zip = unzipSync(new Uint8Array(buffer));
    } catch (err) {
      throw new IngestError(
        INGEST_ERROR_CODES.EXTRACT_FAILED,
        `This file could not be opened — it may be corrupt or password-protected (${err.message}).`,
      );
    }

    // What the package actually is beats what the upload claimed.
    format = detectOoxmlFormat(zip);
    if (!format) {
      throw new IngestError(
        INGEST_ERROR_CODES.EXTRACT_FAILED,
        'This does not look like a Word, Excel or PowerPoint file.',
      );
    }

    if (format === 'docx') sections = extractDocx(zip);
    else if (format === 'xlsx') sections = extractXlsx(zip);
    else sections = extractPptx(zip);
  }

  const { unit, limitUnit, label } = OFFICE_FORMATS[format];

  if (sections.length === 0) {
    throw new IngestError(
      INGEST_ERROR_CODES.EMPTY_CONTENT,
      `No readable text could be found in this ${label.toLowerCase()}.`,
    );
  }

  // Charged against the same free-plan allowance a PDF's pages are, and checked
  // AFTER extraction rather than before: unlike a PDF, none of these formats
  // records how many parts it has without reading them.
  if (planTier !== 'plus' && sections.length > FREE_SECTION_LIMIT) {
    throw new IngestError(
      INGEST_ERROR_CODES.PAGE_LIMIT_EXCEEDED,
      `Free plan allows up to ${FREE_SECTION_LIMIT} ${limitUnit} per document ` +
        `(this one has ${sections.length}). Please upgrade to Plus for larger documents.`,
      { sectionCount: sections.length, limit: FREE_SECTION_LIMIT, unit },
    );
  }

  const fullText = sections.map((section) => section.text).join('\n\n').trim();

  if (!fullText) {
    throw new IngestError(
      INGEST_ERROR_CODES.EMPTY_CONTENT,
      `No readable text could be found in this ${label.toLowerCase()}.`,
    );
  }

  return { format, label, unit, sectionCount: sections.length, sections, fullText };
};
