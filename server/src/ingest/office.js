/**
 * Plain text is one section. It has no numbered parts to cite, and inventing
 * some by counting lines would give the tutor a "section 4" that corresponds to
 * nothing the student can find in their file.
 */
const extractPlainText = (buffer) => {
  const text = buffer.toString('utf8').replace(/\r\n/g, '\n').trim();
  return text ? [{ number: 1, title: null, text }] : [];
};

