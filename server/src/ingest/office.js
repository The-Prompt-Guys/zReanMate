import { readFile } from 'node:fs/promises';

import { unzipSync, strFromU8 } from 'fflate';

import { INGEST_ERROR_CODES, IngestError } from './errors.js';

/**
 * Text extraction for Office documents and plain text files.
 *
 * Word, Excel and PowerPoint are all the same thing underneath — a ZIP of XML
 * parts (OOXML) — so they share one reader here rather than pulling in three
 * libraries that each bundle their own. PowerPoint has no mature extractor on
 * npm anyway, so at least part of this had to be written either way.
 *
 * What the three have in common beyond the container is the unit a student
 * cites: a slide, a sheet, a page. Each extractor below returns numbered
 * `sections`, which chunk exactly like PDF pages do, so "Source: Week 3.pptx,
 * slide 12" works the same way "page 12" already does.
 *
 * XML is read with regular expressions rather than a parser. That is a real
 * constraint and worth naming: it works here because these parts are
 * machine-generated by Office, never hand-written, and only the text runs are
 * being pulled out — no attributes to resolve, no namespaces to honour, no
 * structure to rebuild. A general XML parser would be the right call the moment
 * that stops being true.
 */

const FREE_SECTION_LIMIT = 50;

/** Plain-text formats, which never reach the ZIP path. */
const PLAIN_TEXT_MIME_TYPES = new Set([
  'text/plain',
  'text/markdown',
  'text/csv',
]);

/**
 * The formats this module reads, and what to call each one.
 *
 * `unit` is the word a student sees for a numbered part, because "page 4" of a
 * spreadsheet means nothing. `limitUnit` is the plural for the plan-limit
 * message.
 */
export const OFFICE_FORMATS = {
  docx: {
    mimeType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
    label: 'Word document',
    unit: 'section',
    limitUnit: 'sections',
  },
  xlsx: {
    mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
    label: 'Excel spreadsheet',
    unit: 'sheet',
    limitUnit: 'sheets',
  },
  pptx: {
    mimeType: 'application/vnd.openxmlformats-officedocument.presentationml.presentation',
    label: 'PowerPoint presentation',
    unit: 'slide',
    limitUnit: 'slides',
  },
  text: {
    mimeType: 'text/plain',
    label: 'Text file',
    unit: 'section',
    limitUnit: 'sections',
  },
};

// ---------------------------------------------------------------------------
// XML helpers
// ---------------------------------------------------------------------------

/**
 * The five predefined XML entities, plus numeric references.
 *
 * `&amp;` is unescaped LAST and deliberately: doing it first would turn a
 * literal `&amp;lt;` — which is how a document containing the text "&lt;"
 * stores it — into `<`, injecting markup into what should stay as characters.
 */
const decodeXmlEntities = (text) =>
  String(text)
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&#x([0-9a-fA-F]+);/g, (_, hex) => String.fromCodePoint(Number.parseInt(hex, 16)))
    .replace(/&#(\d+);/g, (_, dec) => String.fromCodePoint(Number.parseInt(dec, 10)))
    .replace(/&amp;/g, '&');

/**
 * Pulls the text out of every `<tag>...</tag>` in document order.
 *
 * The tag is matched with an optional namespace prefix, because the same run
 * element is `<w:t>` in Word and `<a:t>` in PowerPoint drawings, and some
 * producers emit it unprefixed.
 */
const textRuns = (xml, tag) => {
  const pattern = new RegExp(`<(?:[a-zA-Z0-9]+:)?${tag}(?:\\s[^>]*)?>([\\s\\S]*?)</(?:[a-zA-Z0-9]+:)?${tag}>`, 'g');
  const runs = [];
  let match;
  while ((match = pattern.exec(xml)) !== null) runs.push(decodeXmlEntities(match[1]));
  return runs;
};

/** Splits a document into the elements named by `tag`, keeping their markup. */
const elements = (xml, tag) => {
  const pattern = new RegExp(`<(?:[a-zA-Z0-9]+:)?${tag}(?:\\s[^>]*)?>[\\s\\S]*?</(?:[a-zA-Z0-9]+:)?${tag}>`, 'g');
  return xml.match(pattern) ?? [];
};

/** Reads one attribute off an element's opening tag. */
const attribute = (element, name) =>
  new RegExp(`\\s${name}="([^"]*)"`).exec(element)?.[1] ?? null;

/** Files in an OOXML package are named with forward slashes, always. */
const entry = (zip, path) => zip[path];

const textOf = (zip, path) => {
  const file = entry(zip, path);
  return file ? strFromU8(file) : null;
};

