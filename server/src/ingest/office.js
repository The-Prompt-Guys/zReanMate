// Word
// ---------------------------------------------------------------------------

/**
 * Word has no pages.
 *
 * Pagination is a property of rendering, not of the file — the page a
 * paragraph lands on depends on the font and paper size of whoever opens it,
 * and `document.xml` records nothing about it. So a Word document is divided
 * into numbered SECTIONS of roughly `paragraphsPerSection` paragraphs, and the
 * unit is named "section" rather than "page" so a citation never claims a
 * precision the format cannot support.
 */
const extractDocx = (zip, { paragraphsPerSection = 40 } = {}) => {
  const xml = textOf(zip, 'word/document.xml');
  if (xml === null) {
    throw new IngestError(
      INGEST_ERROR_CODES.EXTRACT_FAILED,
      'This Word file is missing its document body and may be corrupt.',
    );
  }

  const paragraphs = [];

  for (const paragraph of elements(xml, 'p')) {
    // A tab between cells keeps a table row readable on one line instead of
    // collapsing its cells into a single run-on string.
    const isTableRow = /<(?:[a-zA-Z0-9]+:)?tc[\s>]/.test(paragraph);
    const runs = textRuns(paragraph, 't');
    if (runs.length === 0) continue;

    const line = runs.join('').replace(/\s+/g, ' ').trim();
    if (line) paragraphs.push(isTableRow ? line : line);
  }

  // Table cells are their own <w:p> elements nested in rows, so a row arrives
  // as several paragraphs. Joining them is not worth the fidelity risk — each
  // cell reads as its own line, which chunks fine and cites fine.
  const sections = [];
  for (let i = 0; i < paragraphs.length; i += paragraphsPerSection) {
    const body = paragraphs.slice(i, i + paragraphsPerSection).join('\n').trim();
    if (body) {
      // Sections are this module's own division of a continuous document, so
      // unlike slides and sheets they genuinely are sequential with no gaps.
      sections.push({ number: sections.length + 1, title: null, text: body });
    }
  }

  return sections;
};

// ---------------------------------------------------------------------------
// Excel
// ---------------------------------------------------------------------------

/**
 * Excel stores most strings once, in a shared table, and cells hold indices
 * into it. A cell with `t="s"` means "look this up"; without it the value is
 * inline. Reading the value as literal text in the shared case yields a
 * spreadsheet full of integers, which is the classic way this goes wrong.
 */
const sharedStrings = (zip) => {
  const xml = textOf(zip, 'xl/sharedStrings.xml');
  if (!xml) return [];
  // One <si> may hold several <t> runs when parts of the cell are formatted
  // differently; they are one string and are joined.
  return elements(xml, 'si').map((si) => textRuns(si, 't').join(''));
};

/**
 * Dates are stored as a number of days since 1899-12-30 and are only dates
 * because of the cell's number format. Left alone they read as "45678", which
 * tells a student nothing and would have the model inventing meaning for it.
 *
 * The built-in date formats are ids 14-22 and 45-47; anything custom is
 * detected by looking for date tokens in its format string.
 */
const BUILTIN_DATE_FORMATS = new Set([14, 15, 16, 17, 18, 19, 20, 21, 22, 45, 46, 47]);

const dateFormatIds = (zip) => {
  const xml = textOf(zip, 'xl/styles.xml');
  if (!xml) return new Set();

  const customDateFormats = new Set();
  for (const numFmt of elements(xml, 'numFmts')) {
    for (const format of numFmt.match(/<(?:[a-zA-Z0-9]+:)?numFmt\s[^>]*\/>/g) ?? []) {
      const id = Number.parseInt(attribute(format, 'numFmtId') ?? '', 10);
      const code = attribute(format, 'formatCode') ?? '';
      // A format is a date format if it positions date tokens. Stripping
      // quoted literals first stops the "m" in a label like "Month" counting.
      const withoutLiterals = code.replace(/"[^"]*"/g, '');
      if (/[dmyhs]/i.test(withoutLiterals) && !/^[#0.,%\s]*$/.test(withoutLiterals)) {
        customDateFormats.add(id);
      }
    }
  }

  // cellXfs is positional: a cell's s="4" is an index into this list.
  const cellXfs = elements(xml, 'cellXfs')[0] ?? '';
  const styles = [];
  for (const xf of cellXfs.match(/<(?:[a-zA-Z0-9]+:)?xf\s[^>]*\/?>/g) ?? []) {
    styles.push(Number.parseInt(attribute(xf, 'numFmtId') ?? '0', 10));
  }

  const dateStyleIndices = new Set();
  styles.forEach((numFmtId, index) => {
    if (BUILTIN_DATE_FORMATS.has(numFmtId) || customDateFormats.has(numFmtId)) {
      dateStyleIndices.add(index);
    }
  });
  return dateStyleIndices;
};

/**
 * Excel's day 0 is 1899-12-30, not 1900-01-01 — the offset absorbs a leap-year
 * bug Lotus 1-2-3 had that Excel keeps for compatibility.
 */
const EXCEL_EPOCH_MS = Date.UTC(1899, 11, 30);

const serialToDate = (serial) => {
  const ms = EXCEL_EPOCH_MS + serial * 86_400_000;
  const date = new Date(ms);
  if (Number.isNaN(date.getTime())) return String(serial);
  const iso = date.toISOString();
  // A whole number is a date; a fraction carries a time of day worth keeping.
  return Number.isInteger(serial) ? iso.slice(0, 10) : iso.slice(0, 16).replace('T', ' ');
};

/** The column letters from a cell reference like "BC12". */
const columnOf = (reference) => /^([A-Z]+)/.exec(reference ?? '')?.[1] ?? '';
const rowOf = (reference) => Number.parseInt(/(\d+)$/.exec(reference ?? '')?.[1] ?? '0', 10);

/**
 * One sheet becomes one numbered section, its rows as tab-separated lines.
 *
 * Tabs rather than commas because cell values routinely contain commas, and a
 * student's spreadsheet is a table whose columns mean something — collapsing
 * them loses the association between a term and its definition, which is
 * exactly what a study kit is built from.
 */
const extractSheet = (xml, strings, dateStyles) => {
  const lines = [];

  for (const row of elements(xml, 'row')) {
    const cells = [];
    // Self-closing <c/> cells are empty and carry no <v>, so both shapes match.
    for (const cell of row.match(/<(?:[a-zA-Z0-9]+:)?c(?:\s[^>]*)?(?:\/>|>[\s\S]*?<\/(?:[a-zA-Z0-9]+:)?c>)/g) ?? []) {
      const type = attribute(cell, 't');
      const styleIndex = Number.parseInt(attribute(cell, 's') ?? '', 10);
      const reference = attribute(cell, 'r');

      let value;
      if (type === 's') {
        const index = Number.parseInt(textRuns(cell, 'v')[0] ?? '', 10);
        value = strings[index] ?? '';
      } else if (type === 'inlineStr') {
        value = textRuns(cell, 't').join('');
      } else if (type === 'str') {
        // A formula's cached result.
        value = textRuns(cell, 'v')[0] ?? '';
      } else if (type === 'b') {
        value = textRuns(cell, 'v')[0] === '1' ? 'TRUE' : 'FALSE';
      } else {
        const raw = textRuns(cell, 'v')[0];
        if (raw === undefined) {
          value = '';
        } else if (!Number.isNaN(styleIndex) && dateStyles.has(styleIndex) && raw !== '') {
          value = serialToDate(Number.parseFloat(raw));
        } else {
          value = raw;
        }
      }

      if (value !== '' && value !== undefined) {
        cells.push({ column: columnOf(reference), value: String(value).replace(/\s+/g, ' ').trim() });
      }
    }

    if (cells.length > 0) {
      lines.push({ row: rowOf(attribute(row, 'r')), text: cells.map((c) => c.value).join('\t') });
    }
  }

  return lines
    .filter((line) => line.text.trim())
    .map((line) => line.text)
    .join('\n');
};

/**
 * Sheet order comes from workbook.xml, not from the order of files in the ZIP.
 * A workbook whose sheets were reordered in Excel keeps its original file names,
 * so reading the directory would number them wrongly.
 */
const extractXlsx = (zip) => {
  const workbook = textOf(zip, 'xl/workbook.xml');
  if (workbook === null) {
    throw new IngestError(
      INGEST_ERROR_CODES.EXTRACT_FAILED,
      'This Excel file is missing its workbook and may be corrupt.',
    );
  }

  const strings = sharedStrings(zip);
  const dateStyles = dateFormatIds(zip);

  // r:id -> target path, from the workbook's relationships.
  const relsXml = textOf(zip, 'xl/_rels/workbook.xml.rels') ?? '';
  const relationships = new Map();
  for (const rel of relsXml.match(/<Relationship\s[^>]*\/?>/g) ?? []) {
    const id = attribute(rel, 'Id');
    const target = attribute(rel, 'Target');
    if (id && target) relationships.set(id, target.replace(/^\/?xl\//, '').replace(/^\//, ''));
  }

  const sections = [];
  const sheetElements = workbook.match(/<(?:[a-zA-Z0-9]+:)?sheet\s[^>]*\/?>/g) ?? [];

  sheetElements.forEach((sheet, index) => {
    const name = attribute(sheet, 'name') ?? `Sheet${index + 1}`;
    const relationshipId = attribute(sheet, 'r:id') ?? attribute(sheet, 'id');
    const target = relationshipId ? relationships.get(relationshipId) : null;
    const path = `xl/${target ?? `worksheets/sheet${index + 1}.xml`}`;

    const sheetXml = textOf(zip, path);
    if (sheetXml === null) return;

    const body = extractSheet(sheetXml, strings, dateStyles);
    if (body.trim()) {
      // The sheet name leads the section: it is often the only label saying
      // what the table is, and a citation reads better with it.
      sections.push({
        // Position in the workbook, not a count of the sheets that had
        // content: an empty sheet in the middle must not renumber the ones
        // after it, or a citation opens the wrong tab.
        number: index + 1,
        title: name,
        text: `${name}\n${body}`,
      });
    }
  });

  return sections;
};

